"""Join synthesized segments into one voice track and write the Remotion timeline."""
import json, os, sys
import numpy as np, soundfile as sf

SRC = sys.argv[1]                       # folder with 000.wav ... + segs.json
PUB = "../video/public/chaiten"
TS = "../video/src/chaiten/timeline.ts"
SR, FPS = 24000, 30
CARD, GAP_SENT, GAP_TURN, TAIL = 3.0, 0.45, 0.9, 3.0

segs = json.load(open(os.path.join(SRC, "segs.json")))
titles = {}
for line in open("guion.txt", encoding="utf-8"):
    if line.startswith("#B"):
        n, t = line[2:].strip().split(" ", 1); titles[int(n)] = t

def trim(w, thr=0.012):
    idx = np.where(np.abs(w) > thr)[0]
    if len(idx) == 0: return w
    a = max(0, idx[0] - int(0.03 * SR)); b = min(len(w), idx[-1] + int(0.08 * SR))
    return w[a:b]

parts, out_segs, blocks = [], [], []
t = 0.0
def add(x):
    global t
    parts.append(x); t += len(x) / SR
def silence(s): add(np.zeros(int(s * SR), dtype=np.float32))

prev = None
for i, sg in enumerate(segs):
    if prev is None or sg["block"] != prev["block"]:
        if prev is not None: silence(0.6)
        blocks.append({"n": sg["block"], "title": titles[sg["block"]], "start": round(t, 3)})
        silence(CARD)
    elif sg["spk"] != prev["spk"]:
        silence(GAP_TURN)
    else:
        silence(GAP_SENT)
    w, sr = sf.read(os.path.join(SRC, f"{i:03d}.wav"), dtype="float32")
    assert sr == SR
    w = trim(w)
    rms = np.sqrt(np.mean(w[np.abs(w) > 0.02] ** 2) + 1e-9)
    w = np.clip(w * (0.12 / rms), -0.98, 0.98)
    start = t; add(w)
    out_segs.append({"spk": sg["spk"], "text": sg["text"], "start": round(start, 3), "end": round(t, 3), "block": sg["block"]})
    prev = sg
silence(TAIL)
voice = np.concatenate(parts)

# mouth envelope per video frame (from the voice only)
hop = SR // FPS
n = len(voice) // hop + 1
env = np.array([np.sqrt(np.mean(voice[k * hop:(k + 1) * hop] ** 2)) if k * hop < len(voice) else 0 for k in range(n)])
env = np.clip(env / (np.percentile(env[env > 0.01], 90) + 1e-9), 0, 1)

# quiet low rumble of the eruption under the voices
rng = np.random.default_rng(7)
brown = np.cumsum(rng.standard_normal(len(voice))).astype(np.float32)
brown -= np.convolve(brown, np.ones(4801) / 4801, mode="same")
brown /= np.abs(brown).max() + 1e-9
mix = voice + brown * 0.035
mix = mix / max(1.0, np.abs(mix).max() / 0.97)

os.makedirs(PUB, exist_ok=True)
sf.write(os.path.join(PUB, "voces.wav"), mix, SR)
dur = len(mix) / SR
with open(TS, "w") as f:
    f.write("// AUTO-GENERATED by chaiten/assemble.py from the synthesized voice track.\n")
    f.write('import type { SpeakerId } from "./cast";\n')
    f.write("export type Seg = { spk: SpeakerId; text: string; start: number; end: number; block: number };\n")
    f.write(f"export const BLOCKS: {{ n: number; title: string; start: number }}[] = {json.dumps(blocks, ensure_ascii=False)};\n")
    f.write(f"export const SEGS: Seg[] = {json.dumps(out_segs, ensure_ascii=False)};\n")
    f.write(f"export const ENV: number[] = {json.dumps([round(float(x), 2) for x in env])};\n")
    f.write(f"export const DURATION = {dur:.2f};\nexport const HAS_AUDIO = true;\n")
print(f"duration {dur:.1f}s = {dur/60:.2f} min, {len(out_segs)} segs")
